/**
 * Clase que representa una moneda de 1000 pesos.
 * Hereda de la clase Moneda.
 */
public class Moneda1000 extends Moneda {

    /**
     * Retorna el valor de la moneda, que es 1000 pesos.
     *
     * @return Valor de la moneda (1000).
     */
    @Override
    public int getValor() {
        return 1000;
    }
}